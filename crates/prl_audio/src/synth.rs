//! Placeholder sound effects synthesized in code as 16-bit mono WAV bytes.
//!
//! No third-party or recorded audio is used. These are disposable test sounds,
//! not a sound direction.

/// Sample rate of every generated placeholder sound.
pub const SAMPLE_RATE: u32 = 22_050;

/// One placeholder sound cue.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Sfx {
    /// Ordinary melee hit: short noise burst.
    Hit,
    /// Critical hit: brighter, sharper click over noise.
    Crit,
    /// Glancing blow: soft low thud.
    Glance,
    /// An actor died: low falling tone.
    Death,
    /// Interface tick (door opened, new run).
    Ui,
}

impl Sfx {
    /// Every cue, in a stable order.
    pub const ALL: [Self; 5] = [Self::Hit, Self::Crit, Self::Glance, Self::Death, Self::Ui];

    /// Deterministic WAV file bytes for this cue.
    #[must_use]
    pub fn wav(self) -> Vec<u8> {
        wav_bytes(&self.samples(), SAMPLE_RATE)
    }

    fn samples(self) -> Vec<i16> {
        let mut noise = Noise(0x9E37_79B9);
        match self {
            Self::Hit => render(90, |t, phase| {
                let decay = (1.0 - t).powi(3);
                0.55 * decay * noise.next() + 0.25 * decay * sine(phase, 180.0)
            }),
            Self::Crit => render(130, |t, phase| {
                let decay = (1.0 - t).powi(2);
                0.4 * decay * noise.next() + 0.4 * decay * square(phase, 1200.0)
            }),
            Self::Glance => render(70, |t, phase| 0.35 * (1.0 - t).powi(4) * sine(phase, 110.0)),
            Self::Death => render(450, |t, phase| {
                // Falling pitch from 220 Hz to 110 Hz.
                let frequency = 220.0 - 110.0 * t;
                0.4 * (1.0 - t) * sine(phase * frequency / 220.0, 220.0)
            }),
            Self::Ui => render(30, |t, phase| 0.2 * (1.0 - t) * sine(phase, 1500.0)),
        }
    }
}

/// Evaluates `voice(progress 0..1, seconds)` for `millis` of audio.
fn render(millis: u16, mut voice: impl FnMut(f32, f32) -> f32) -> Vec<i16> {
    let count = u16::try_from(u32::from(millis) * SAMPLE_RATE / 1000).unwrap_or(u16::MAX);
    let rate = f32::from(u16::try_from(SAMPLE_RATE).unwrap_or(u16::MAX));
    (0..count)
        .map(|index| {
            let t = f32::from(index) / f32::from(count);
            to_pcm(voice(t, f32::from(index) / rate))
        })
        .collect()
}

fn sine(seconds: f32, frequency: f32) -> f32 {
    (std::f32::consts::TAU * frequency * seconds).sin()
}

fn square(seconds: f32, frequency: f32) -> f32 {
    if sine(seconds, frequency) >= 0.0 {
        1.0
    } else {
        -1.0
    }
}

#[expect(
    clippy::cast_possible_truncation,
    reason = "Input is clamped to -1..=1 so the scaled value fits i16"
)]
fn to_pcm(sample: f32) -> i16 {
    (sample.clamp(-1.0, 1.0) * f32::from(i16::MAX)) as i16
}

/// Fixed-seed xorshift noise so generated bytes are reproducible.
struct Noise(u32);

impl Noise {
    fn next(&mut self) -> f32 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        self.0 = x;
        // Top 16 bits mapped to -1..1.
        f32::from(u16::try_from(x >> 16).unwrap_or(0)) / 32_767.5 - 1.0
    }
}

/// Encodes 16-bit mono PCM samples as a canonical 44-byte-header WAV file.
#[must_use]
pub fn wav_bytes(samples: &[i16], sample_rate: u32) -> Vec<u8> {
    let data_len = u32::try_from(samples.len().saturating_mul(2)).unwrap_or(u32::MAX - 36);
    let mut bytes = Vec::with_capacity(44 + samples.len() * 2);
    bytes.extend_from_slice(b"RIFF");
    bytes.extend_from_slice(&(36 + data_len).to_le_bytes());
    bytes.extend_from_slice(b"WAVEfmt ");
    bytes.extend_from_slice(&16_u32.to_le_bytes());
    bytes.extend_from_slice(&1_u16.to_le_bytes()); // PCM
    bytes.extend_from_slice(&1_u16.to_le_bytes()); // mono
    bytes.extend_from_slice(&sample_rate.to_le_bytes());
    bytes.extend_from_slice(&(sample_rate * 2).to_le_bytes()); // byte rate
    bytes.extend_from_slice(&2_u16.to_le_bytes()); // block align
    bytes.extend_from_slice(&16_u16.to_le_bytes()); // bits per sample
    bytes.extend_from_slice(b"data");
    bytes.extend_from_slice(&data_len.to_le_bytes());
    for sample in samples {
        bytes.extend_from_slice(&sample.to_le_bytes());
    }
    bytes
}

#[cfg(test)]
mod tests {
    use super::*;

    fn u32_at(bytes: &[u8], offset: usize) -> u32 {
        let mut word = [0; 4];
        word.copy_from_slice(&bytes[offset..offset + 4]);
        u32::from_le_bytes(word)
    }

    #[test]
    fn wav_header_describes_sixteen_bit_mono_pcm() {
        let bytes = wav_bytes(&[0, 1, -1], 8_000);
        assert_eq!(bytes.len(), 44 + 6);
        assert_eq!(&bytes[0..4], b"RIFF");
        assert_eq!(u32_at(&bytes, 4), 36 + 6);
        assert_eq!(&bytes[8..16], b"WAVEfmt ");
        assert_eq!(u32_at(&bytes, 16), 16);
        assert_eq!(&bytes[20..24], &[1, 0, 1, 0]);
        assert_eq!(u32_at(&bytes, 24), 8_000);
        assert_eq!(u32_at(&bytes, 28), 16_000);
        assert_eq!(&bytes[32..36], &[2, 0, 16, 0]);
        assert_eq!(&bytes[36..40], b"data");
        assert_eq!(u32_at(&bytes, 40), 6);
        assert_eq!(&bytes[44..], &[0, 0, 1, 0, 0xFF, 0xFF]);
    }

    #[test]
    fn every_cue_is_short_deterministic_and_distinct() {
        let mut seen = Vec::new();
        for sfx in Sfx::ALL {
            let bytes = sfx.wav();
            assert_eq!(bytes, sfx.wav(), "{sfx:?} must be reproducible");
            let data = u32_at(&bytes, 40);
            assert_eq!(bytes.len(), 44 + data as usize);
            let seconds = f64::from(data) / 2.0 / f64::from(SAMPLE_RATE);
            assert!(seconds > 0.02 && seconds < 0.5, "{sfx:?} lasts {seconds}s");
            assert!(
                bytes[44..].iter().any(|byte| *byte != 0),
                "{sfx:?} is silent"
            );
            assert!(!seen.contains(&bytes));
            seen.push(bytes);
        }
        let hit = Sfx::Hit.samples();
        assert_eq!(hit.len(), 90 * SAMPLE_RATE as usize / 1000);
    }
}
