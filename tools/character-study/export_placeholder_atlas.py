#!/usr/bin/env python3
"""Export the disposable Gravebound placeholder atlas used by the playtest.

Serves this directory locally, renders ``export.html`` in headless Chrome and
writes ``gravebound_placeholder.png`` plus its RON manifest into the base pack.
No network access beyond localhost; outputs are placeholders, not approved art.

Usage: python3 tools/character-study/export_placeholder_atlas.py [--check] [--chrome PATH]
"""

from __future__ import annotations

import argparse
import base64
import functools
import html
import http.server
import json
import re
import shutil
import subprocess
import sys
import tempfile
import threading
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[1] / "assets/packs/prl/sprites/placeholder"
CHROMES = ("google-chrome", "chromium", "chromium-browser", "chrome")


def render(chrome: str) -> dict:
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *args: object) -> None:
            pass

    handler = functools.partial(Quiet, directory=str(HERE))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        with tempfile.TemporaryDirectory() as profile:
            dom = subprocess.run(
                [chrome, "--headless=new", "--disable-gpu", "--no-sandbox", "--no-first-run",
                 f"--user-data-dir={profile}", "--virtual-time-budget=10000", "--dump-dom",
                 f"http://127.0.0.1:{server.server_address[1]}/export.html"],
                check=True, capture_output=True, text=True, timeout=120,
            ).stdout
    finally:
        server.shutdown()
    match = re.search(r'<pre id="result">(.*?)</pre>', dom, re.S)
    if not match or match.group(1) == "pending":
        sys.exit("export.html did not produce an atlas; open it in a browser to see the error")
    return json.loads(html.unescape(match.group(1)))


def ron(value: object, indent: int = 0) -> str:
    pad, inner = "    " * indent, "    " * (indent + 1)
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        if all(isinstance(item, (int, float)) for item in value):
            return "(" + ", ".join(str(item) for item in value) + ")"
        return "[\n" + "".join(f"{inner}{ron(item, indent + 1)},\n" for item in value) + pad + "]"
    if isinstance(value, dict):
        return "{\n" + "".join(f"{inner}{json.dumps(k)}: {ron(v, indent + 1)},\n" for k, v in value.items()) + pad + "}"
    raise TypeError(type(value))


def manifest_ron(manifest: dict) -> str:
    def optional(value: object, indent: int) -> str:
        return "None" if value is None else f"Some({ron(value, indent)})"

    def clip(value: dict, indent: int) -> str:
        pad = "    " * (indent + 1)
        return (f"(\n{pad}frame_ms: {value['frame_ms']},\n{pad}right: {ron(value['right'], indent + 1)},\n"
                f"{pad}left: {optional(value['left'], indent + 1)},\n{'    ' * indent})")

    lines = ["// Generated by tools/character-study/export_placeholder_atlas.py. Do not hand-edit.",
             "// Disposable Gravebound placeholders, not approved production art.",
             "(", f"    schema_version: {manifest['schema_version']},",
             f"    status: {json.dumps(manifest['status'])},",
             f"    source: {json.dumps(manifest['source'])},",
             f"    image: {json.dumps(manifest['image'])},",
             f"    size: {ron(manifest['size'])},", "    actors: {"]
    for key, actor in manifest["actors"].items():
        lines.append(f"        {json.dumps(key)}: (")
        lines.append(f"            offset_y: {actor['offset_y']},")
        lines.append(f"            idle: {clip(actor['idle'], 3)},")
        for name in ("walk", "attack"):
            value = actor[name]
            lines.append(f"            {name}: " + ("None," if value is None else f"Some({clip(value, 3)}),"))
        lines.append("        ),")
    lines.append("    },")
    lines.append("    tiles: {")
    for key, tile in manifest["tiles"].items():
        lines.append(f"        {json.dumps(key)}: (rect: {ron(tile['rect'])}, offset_y: {tile['offset_y']}, "
                     f"open: {optional(tile['open'], 0)}),")
    lines.append("    },")
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if committed outputs differ")
    parser.add_argument("--chrome", help="Chrome/Chromium executable")
    args = parser.parse_args()
    chrome = args.chrome or next((path for name in CHROMES if (path := shutil.which(name))), None)
    if not chrome:
        sys.exit("Chrome or Chromium is required; pass --chrome PATH")
    result = render(chrome)
    manifest = result["manifest"]
    png = base64.b64decode(result["png"].split(",", 1)[1])
    outputs = {OUTPUT / manifest["image"]: png,
               OUTPUT / "gravebound_placeholder.ron": manifest_ron(manifest).encode()}
    if args.check:
        stale = [str(path) for path, data in outputs.items() if not path.exists() or path.read_bytes() != data]
        if stale:
            sys.exit("Placeholder atlas is stale; re-run the exporter:\n" + "\n".join(stale))
        print("Placeholder atlas is up to date.")
        return
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path, data in outputs.items():
        path.write_bytes(data)
        print(f"wrote {path.relative_to(HERE.parents[1])} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
